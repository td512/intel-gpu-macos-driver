#!/usr/bin/env python3
"""names.py map.tsv thunks.h > backend_names.h: for every dispatch entry the GL name a backend (zink, eglGetProcAddress) should
resolve. Several symbols can share an entry (glUseProgram, glUseProgramObjectARB): the core name is preferred."""
import re, sys
by = {}
for l in open(sys.argv[1]):
    p = l.rstrip('\n').split('\t')
    if len(p) == 3: by.setdefault(int(p[1]), []).append(p[0])
def rank(s):
    suf = re.search(r'(ARB|EXT|APPLE|ATI|NV|SGIS|IBM)$', s)
    return (1 if suf else 0, len(s), s)
n = int(re.search(r'#define CGLT_N (\d+)', open(sys.argv[2]).read()).group(1))
print('// generated by names.py from map.tsv (measured against libGL): NULL = no symbol reaches this entry')
print('static const char *cglt_names[%d] = {' % n)
for i in range(n):
    c = sorted(by.get(i, []), key=rank)
    print('  ' + (f'"{c[0]}",' if c else 'NULL,') + (f' // also {" ".join(c[1:])}' if len(c) > 1 else ''))
print('};')
